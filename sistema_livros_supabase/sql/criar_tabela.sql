-- Execute este script no SQL Editor do Supabase.
create table if not exists public.livros (
  id bigint generated by default as identity primary key,
  titulo varchar(150) not null,
  autor varchar(120) not null,
  ano integer,
  genero varchar(80),
  descricao varchar(1000),
  created_at timestamptz not null default now()
);

-- Ative RLS. Para um projeto escolar de demonstração, esta política permite
-- operações públicas usando a chave anon. NÃO use esta política em produção.
alter table public.livros enable row level security;

create policy "Acesso público para atividade escolar"
on public.livros
for all
to anon
using (true)
with check (true);

grant select, insert, update, delete on public.livros to anon;
grant usage, select on sequence public.livros_id_seq to anon;
